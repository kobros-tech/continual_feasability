"""
Stage 3b pipeline:  cases/*.json -> exact solver -> candidate certificate -> Certs.lean

Certs.lean is checked by the Lean kernel (`decide +kernel`, via `ArrSys.checkYes/checkNo`).
The solver is untrusted; nothing here is a verdict until Lean accepts it.

  python3 solver/pipeline.py            # (re)generate Certs.lean at the repo root
  python3 solver/pipeline.py --check    # fail if the committed Certs.lean is stale

Per case:
  YES / NO  -> an `accepted` theorem (checker = true) and a soundness theorem
               (checkYes_sound / checkNo_sound), then
               `*_rejected` theorems (deliberately invalid certificates, = false) and, kept
               apart and labeled, `*_still_valid` (mutations that remain valid, = true).
  SOLVER_FAILURE -> NO theorem is emitted. A failure is never a verdict.
Plus deliberately invalid certificates. Each is emitted with the expected value computed by
the independent Python verifier, so Lean agreeing with it is a cross-check; cross-system
certificates (YES witness offered for a NO system and vice versa) must be false by
exclusivity, which is asserted here.
"""
import glob, json, os, re, sys
from fractions import Fraction as Q

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
from exact_solver import (parse_system, solve_and_verify, verify_yes, verify_no,
                          YES, NO, FAIL)

OUT = os.path.join(ROOT, "Certs.lean")


def lq(x):
    x = Q(x)
    if x.denominator == 1:
        return str(x.numerator)
    return f"({x.numerator}/{x.denominator})"

def larr(xs):
    return "#[" + ", ".join(lq(x) for x in xs) + "]"

def lmat(C):
    return "#[" + ", ".join(larr(r) for r in C) + "]"

def ident(name):
    assert re.fullmatch(r"[a-z][a-z0-9_]*", name), f"bad case name {name!r}"
    return name


def mutations_yes(b, m):
    out = {"len_plus": b + [Q(0)], "empty": []}
    if b:
        out["len_minus"] = b[:-1]
        out["negated"] = [-x for x in b]
        out["shifted"] = [b[0] + 1] + b[1:]
    out["zeros"] = [Q(0)] * len(b)
    return out

def mutations_no(l):
    out = {"len_plus": l + [Q(0)], "empty": [], "zeros": [Q(0)] * len(l),
           "negated": [-x for x in l]}
    if l:
        out["len_minus"] = l[:-1]
    for i, x in enumerate(l):
        if x != 0:
            out["first_halved"] = l[:i] + [x / 2] + l[i + 1:]
            break
    return out


def build():
    files = sorted(glob.glob(os.path.join(HERE, "cases", "*.json")))
    assert files, "no cases found"
    lines, report, nthm = [], [], 0
    lines += [
        "import ContinualFeasibility",
        "",
        "/-!",
        "AUTO-GENERATED by `solver/pipeline.py` -- do not edit; regenerate instead.",
        "CI regenerates this file and fails if the committed copy differs.",
        "",
        "Stage 3b: certificates proposed by the UNTRUSTED exact-rational solver, accepted or",
        "rejected only by the Lean array checker (`decide +kernel`, no `native_decide`).",
        "SOLVER_FAILURE cases emit no theorem: a resource failure is not a verdict.",
        "-/",
        "",
        "open ContinualFeasibility ContinualFeasibility.ArrSys",
        "",
    ]
    axioms = []
    for path in files:
        name = ident(os.path.splitext(os.path.basename(path))[0])
        with open(path) as f:
            j = json.load(f)
        C, d, m, n = parse_system(j)
        expect = j.get("expect")
        assert expect in (YES, NO, FAIL), f"{name}: missing/invalid 'expect'"
        kw = {k: j[k] for k in ("max_pivots", "time_limit") if k in j}
        status, payload, stats = solve_and_verify(C, d, m, n, **kw)
        assert status == expect, f"{name}: solver said {status}, expected {expect}"
        report.append((name, status, stats.get("pivots", "-")))

        if status == FAIL:
            lines += [f"-- {name}: SOLVER_FAILURE ({payload}); no certificate, no verdict.", ""]
            continue

        S = f"s_{name}"
        lines += [f"-- {name}: {status}  (m={m}, n={n}, pivots={stats['pivots']})",
                  f"def {S} : ArrSys := {{ m := {m}, n := {n}, C := {lmat(C)}, d := {larr(d)} }}"]
        cert = f"c_{name}"
        lines += [f"def {cert} : Array ℚ := {larr(payload)}"]
        thms = []
        if status == YES:
            assert verify_yes(C, d, m, n, payload)
            thms += [f"theorem {name}_accepted : checkYes {S} {cert} = true := by decide +kernel",
                     f"theorem {name}_sound : ∃ b, YesCert (toMat {S}) (toD {S}) b :=\n"
                     f"  checkYes_sound {S} {cert} {name}_accepted"]
            muts = mutations_yes(payload, m)
            chk, ver = "checkYes", lambda c: verify_yes(C, d, m, n, c)
            cross = ("checkNo", "ones_as_no", [Q(1)] * m,
                     lambda c: verify_no(C, d, m, n, c))
        else:
            assert verify_no(C, d, m, n, payload)
            thms += [f"theorem {name}_accepted : checkNo {S} {cert} = true := by decide +kernel",
                     f"theorem {name}_refuted : ¬ ∃ b, YesCert (toMat {S}) (toD {S}) b :=\n"
                     f"  checkNo_sound {S} {cert} {name}_accepted"]
            muts = mutations_no(payload)
            chk, ver = "checkNo", lambda c: verify_no(C, d, m, n, c)
            cross = ("checkYes", "zeros_as_yes", [Q(0)] * n,
                     lambda c: verify_yes(C, d, m, n, c))
        # Mutations are classified by the independent Python verifier, and named for the outcome:
        #   *_rejected    : deliberately invalid certificate, the Lean checker must return false
        #   *_still_valid : a mutation that happens to remain a valid certificate (true)
        rejected, still_valid = [], []
        for tag, c in muts.items():
            if ver(c):
                still_valid.append(f"theorem {name}_{tag}_still_valid : {chk} {S} {larr(c)} = true "
                                   f":= by decide +kernel")
            else:
                rejected.append(f"theorem {name}_{tag}_rejected : {chk} {S} {larr(c)} = false "
                                f":= by decide +kernel")
        ck, tag, c, v = cross
        assert not v(c), f"{name}: exclusivity violated by {tag}"   # YES xor NO
        rejected.append(f"theorem {name}_{tag}_rejected : {ck} {S} {larr(c)} = false := by decide +kernel")
        # a wrong-length vector is ALWAYS invalid (shape check), so every case has known-invalid
        # certificates of the right kind, whatever the other mutations turn out to be
        assert any(t.startswith(f"theorem {name}_len_plus_rejected") for t in rejected), name
        kind = "YES witness" if status == YES else "NO certificate"
        grp = [f"-- valid {kind} (solver output)"] + thms
        grp += ["-- invalid certificates: must be rejected (= false)"] + rejected
        if still_valid:
            grp += ["-- mutations that happen to remain valid (= true); NOT invalid-certificate tests"]
            grp += still_valid
        thms = [t for t in grp if not t.startswith("--")]
        lines += grp + [""]
        nthm += len(thms)
        axioms += [re.match(r"theorem (\S+)", t).group(1) for t in thms]
        continue

    lines += [f"#print axioms {a}" for a in axioms] + [""]
    return "\n".join(lines), report, nthm


def main():
    text, report, nthm = build()
    for name, status, piv in report:
        print(f"{name:28s} {status:15s} pivots={piv}")
    print(f"{nthm} Lean theorems")
    if "--check" in sys.argv:
        cur = open(OUT).read() if os.path.exists(OUT) else None
        if cur != text:
            print("Certs.lean is stale: run `python3 solver/pipeline.py` and commit it.")
            sys.exit(1)
        print("Certs.lean is up to date")
    else:
        with open(OUT, "w") as f:
            f.write(text)
        print("wrote", OUT)

if __name__ == "__main__":
    main()
