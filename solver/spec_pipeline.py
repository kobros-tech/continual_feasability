"""
Stage 3c pipeline:  specs/*.json -> exporter -> untrusted solver -> SpecCerts.lean

For each concrete Spec the generated Lean file proves, in the kernel (`decide +kernel`):
  * `<n>_export_matches`   the independent Python exporter equals the Lean `exportSys` (ArrSys.beq),
  * `<n>_accepted`         the solver's certificate is accepted by checkYes/checkNo ON `exportSys`,
  * `<n>_feasible` / `<n>_infeasible`   the sequential conclusion, via `export_yes` / `export_no`,
  * `<n>_*_rejected`       deliberately invalid certificates are rejected.
Solver failure on a spec emits no theorem and fails the pipeline (specs are expected to be decidable).

  python3 solver/spec_pipeline.py          # regenerate SpecCerts.lean
  python3 solver/spec_pipeline.py --check  # fail if the committed copy is stale
"""
import glob, json, os, re, sys
from fractions import Fraction as Q

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
from exact_solver import solve_and_verify, verify_yes, verify_no, YES, NO, FAIL
from spec_export import parse_spec, export_system
from pipeline import lq, larr, lmat, ident

OUT = os.path.join(ROOT, "SpecCerts.lean")
LIB_THMS = ["exportSys_wf", "exportSys_encodes", "export_yes", "export_no",
            "encodes_yes_iff", "export_feasible_iff", "export_infeasible_iff"]


def vec(xs):                 # ![a, b, ...] for Fin-indexed data
    return "![" + ", ".join(xs) + "]"

def lean_spec(name, S):
    p, K, T, N = S["p"], S["K"], S["T"], S["N"]
    lines = [f"def sp_{name} : Spec {p} {K} {T} {N} where",
             f"  ct := {vec([str(c) for c in S['ct']])}",
             f"  W0 := {vec([vec([lq(v) for v in r]) for r in S['W0']])}",
             f"  x := {vec([vec([lq(v) for v in r]) for r in S['x']])}",
             f"  y := {vec([str(v) for v in S['y']])}",
             f"  et := {vec([str(v) for v in S['et']])}",
             f"  isRef := {vec(['true' if b else 'false' for b in S['isRef']])}",
             f"  γ := {lq(S['gamma'])}",
             "  hγ := by norm_num",
             "  hy := by decide +kernel"]
    return lines


def build():
    files = sorted(glob.glob(os.path.join(HERE, "specs", "*.json")))
    assert files, "no specs"
    L = ["import ContinualFeasibility", "",
         "/-!",
         "AUTO-GENERATED by `solver/spec_pipeline.py` -- do not edit; regenerate instead.",
         "CI regenerates this file and fails if the committed copy differs.",
         "",
         "Stage 3c: concrete sequential `Spec`s exported to arrays by the Lean `exportSys`, compared",
         "with an independent Python exporter, and decided by solver-proposed certificates that only",
         "the Lean array checker accepts (`decide +kernel`, no `native_decide`).",
         "-/", "",
         "open ContinualFeasibility ContinualFeasibility.ArrSys", ""]
    axioms, report, nthm = [], [], 0
    for path in files:
        name = ident(os.path.splitext(os.path.basename(path))[0])
        j = json.load(open(path))
        expect = j.get("expect"); assert expect in (YES, NO), name
        S = parse_spec(j)
        C, d, m, n = export_system(S)
        st, cert, stats = solve_and_verify(C, d, m, n)
        assert st == expect, f"{name}: solver {st} / {cert if st == FAIL else ''}, expected {expect}"
        report.append((name, st, m, n, stats["pivots"]))
        sp, ex, ce = f"sp_{name}", f"ex_{name}", f"cert_{name}"
        L += [f"-- {name}: {st}  (p={S['p']}, K={S['K']}, T={S['T']}, N={S['N']}; "
              f"{m} rows x {n} vars; pivots={stats['pivots']})"]
        L += lean_spec(name, S)
        L += [f"def {ex} : ArrSys := {{ m := {m}, n := {n}, C := {lmat(C)}, d := {larr(d)} }}",
              f"def {ce} : Array ℚ := {larr(cert)}"]
        T_ = [f"theorem {name}_export_matches : ArrSys.beq (exportSys {sp}) {ex} = true := "
              "by decide +kernel"]
        if st == YES:
            assert verify_yes(C, d, m, n, cert)
            T_ += [f"theorem {name}_accepted : checkYes (exportSys {sp}) {ce} = true := by decide +kernel",
                   f"theorem {name}_feasible : ∃ W, Feasible {sp} W :=\n"
                   f"  export_yes {sp} {ce} {name}_accepted"]
            bad = cert + [Q(0)]
            T_ += [f"theorem {name}_len_plus_rejected : checkYes (exportSys {sp}) {larr(bad)} = false := "
                   "by decide +kernel"]
            cross = [Q(1)] * m
            assert not verify_no(C, d, m, n, cross)
            T_ += [f"theorem {name}_ones_as_no_rejected : checkNo (exportSys {sp}) {larr(cross)} = false := "
                   "by decide +kernel"]
        else:
            assert verify_no(C, d, m, n, cert)
            T_ += [f"theorem {name}_accepted : checkNo (exportSys {sp}) {ce} = true := by decide +kernel",
                   f"theorem {name}_infeasible : ¬ ∃ W, Feasible {sp} W :=\n"
                   f"  export_no {sp} {ce} {name}_accepted"]
            bad = cert + [Q(0)]
            T_ += [f"theorem {name}_len_plus_rejected : checkNo (exportSys {sp}) {larr(bad)} = false := "
                   "by decide +kernel"]
            cross = [Q(0)] * n
            assert not verify_yes(C, d, m, n, cross)
            T_ += [f"theorem {name}_zeros_as_yes_rejected : checkYes (exportSys {sp}) {larr(cross)} = false := "
                   "by decide +kernel"]
        L += T_ + [""]
        nthm += len(T_)
        axioms += [re.match(r"theorem (\S+)", t).group(1) for t in T_]
    L += [f"#print axioms ContinualFeasibility.{t}" for t in LIB_THMS]
    L += [f"#print axioms {a}" for a in axioms] + [""]
    return "\n".join(L), report, nthm + len(LIB_THMS)


def main():
    text, report, nthm = build()
    for r in report:
        print("%-18s %-4s rows=%-4d vars=%-3d pivots=%d" % r)
    print(nthm, "audited declarations")
    if "--check" in sys.argv:
        cur = open(OUT).read() if os.path.exists(OUT) else None
        if cur != text:
            print("SpecCerts.lean is stale: run `python3 solver/spec_pipeline.py` and commit it.")
            sys.exit(1)
        print("SpecCerts.lean is up to date")
    else:
        open(OUT, "w").write(text)
        print("wrote", OUT)

if __name__ == "__main__":
    main()
